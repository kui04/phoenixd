#!/system/bin/sh
#
# udhcpc event script.

MODDIR="$(cd "${0%/*}/.." && pwd)"
readonly MODDIR
. "${MODDIR}/scripts/common.sh"

#######################################
# Update nameservers and reload the DNS forwarder.
# Arguments:
#   Space-separated list of DNS servers.
#######################################
update_dns() {
  local d dns_list
  dns_list="${1:-}"
  [ -z "${dns_list}" ] && dns_list='223.5.5.5 223.6.6.6'
  {
    printf '# Generated by udhcpc for %s\n' "${interface}"
    for d in ${dns_list}; do
      printf 'nameserver %s\n' "${d}"
    done
  } >"${HEADLESS_DIR}/resolv.conf.tmp"
  mv -f "${HEADLESS_DIR}/resolv.conf.tmp" "${HEADLESS_DIR}/resolv.conf"

  if [ -d /data/adb/rootfs/etc ]; then
    cp -f "${HEADLESS_DIR}/resolv.conf" \
      /data/adb/rootfs/etc/resolv.conf 2>/dev/null || true
  fi
  if [ -d /data/adb/rootfs/mnt/etc ]; then
    cp -f "${HEADLESS_DIR}/resolv.conf" \
      /data/adb/rootfs/mnt/etc/resolv.conf 2>/dev/null || true
  fi

  sv hup "${SERVICE_DIR}/dns-forwarder" >/dev/null 2>&1 \
    || pkill -HUP dns-forwarder 2>/dev/null || true
}

# udhcpc sets interface, ip, mask and router.
main() {
  case "${1:-}" in
    bound | renew)
      ip addr replace "${ip}/${mask}" dev "${interface}"
      if [ -n "${router:-}" ]; then
        ip route replace default via "${router%% *}" dev "${interface}" onlink
      fi
      sh "${MODDIR}/scripts/net.sh" add
      update_dns "${dns:-}"
      log "lease ${ip}/${mask} via ${router:-none}"
      ;;
    deconfig)
      ip addr flush dev "${interface}"
      ;;
  esac
}

main "$@"
